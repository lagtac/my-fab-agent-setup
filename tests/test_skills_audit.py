"""Process-level tests for scripts/skills_audit.py.

The seam is the process boundary: run the program against fixture skill roots
and assert on exit code, stderr, and the report it writes. Nothing imports the
program's internals.
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "skills_audit.py"


def write_skill(
    root: Path, name: str, description: str, extra_frontmatter: str = ""
) -> Path:
    directory = root / name
    directory.mkdir(parents=True, exist_ok=True)
    header = f"---\nname: {name}\ndescription: {description}\n"
    if extra_frontmatter:
        header += f"{extra_frontmatter}\n"
    header += f"---\n\n# {name}\n"
    (directory / "SKILL.md").write_text(header, encoding="utf-8")
    return directory


COLLISION_HEADER = "## Trigger collisions"


def collision_section(report: str) -> str:
    """Return the overlap section body, without the heading."""
    head, separator, body = report.partition(COLLISION_HEADER)
    if not separator:
        raise AssertionError(f"report has no {COLLISION_HEADER!r} section:\n{report}")
    return body


def run_audit(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(SCRIPT), *args],
        capture_output=True,
        text=True,
        check=False,
    )


class AuditSmokeTest(unittest.TestCase):
    def test_report_keeps_the_cost_table_and_totals(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            work = Path(temporary)
            write_skill(work / "root", "alpha", "Reviews code for correctness.")
            report = work / "report.md"

            result = run_audit("--root", str(work / "root"), "--out", str(report))

            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertIn("wrote", result.stderr)
            text = report.read_text(encoding="utf-8")
            self.assertTrue(text.startswith("# Skills audit\n"), text)
            self.assertIn("Generated by `scripts/skills_audit.py`. Do not edit.", text)
            self.assertIn(
                "| # | Skill | Source | Load (tok) | Catalogue (tok) | Shadowed |", text
            )
            self.assertIn("| alpha |", text)
            self.assertIn("**Skills:** 1", text)
            self.assertIn("**Total load:**", text)
            self.assertIn("**Catalogue (always on):**", text)

    def test_missing_root_warns_and_still_writes_the_report(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            work = Path(temporary)
            write_skill(work / "root", "alpha", "Reviews code for correctness.")
            report = work / "report.md"

            result = run_audit(
                "--root",
                str(work / "absent"),
                "--root",
                str(work / "root"),
                "--out",
                str(report),
            )

            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertIn("warning: skipping missing root", result.stderr)
            self.assertIn("| alpha |", report.read_text(encoding="utf-8"))

    def test_write_error_exits_two(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            work = Path(temporary)
            write_skill(work / "root", "alpha", "Reviews code for correctness.")
            target = work / "directory"
            target.mkdir()

            result = run_audit("--root", str(work / "root"), "--out", str(target))

            self.assertEqual(result.returncode, 2, result.stderr)
            self.assertIn("error: cannot write", result.stderr)

    def test_empty_corpus_exits_two(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            empty = Path(temporary) / "empty"
            empty.mkdir()

            result = run_audit("--root", str(empty))

            self.assertEqual(result.returncode, 2, result.stderr)
            self.assertIn("error: no skills found", result.stderr)


COLLIDING = (
    ("alpha", "Reviews frontend accessibility, keyboard navigation, and focus states."),
    ("beta", "Reviews frontend accessibility, keyboard navigation, and focus order."),
)
APART = (
    ("gamma", "Drafts release notes and upgrade guides for maintainers."),
    ("delta", "Debugging database migrations and schema drift."),
)
# Union of 10 tokens, 4 shared: Jaccard exactly 0.4.
AT_THRESHOLD = (
    ("epsilon", "Writes technical documentation, ship changelog entries, notes."),
    ("zeta", "Writes technical documentation, tests coverage, ship badges."),
)
# Union of 9 tokens, 3 shared: Jaccard just below the default threshold, at 0.33.
JUST_BELOW = (
    ("eta", "Reviews database query plans and index statistics."),
    ("theta", "Reviews database backup schedules and index rebuilds."),
)

FIXTURES = COLLIDING + APART + AT_THRESHOLD + JUST_BELOW


class CollisionSectionTest(unittest.TestCase):
    def audit(self, work: Path, *args: str, skills=FIXTURES) -> str:
        root = work / "root"
        root.mkdir(exist_ok=True)
        for name, description in skills:
            write_skill(root, name, description)
        report = work / "report.md"
        result = subprocess.run(
            [
                sys.executable,
                str(SCRIPT),
                "--root",
                str(root),
                "--out",
                str(report),
                *args,
            ],
            capture_output=True,
            text=True,
            check=False,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        return report.read_text(encoding="utf-8")

    def test_pairs_at_or_above_the_default_threshold_are_scored(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            section = collision_section(self.audit(Path(temporary)))

            self.assertIn("| 0.75 | alpha | beta |", section)
            self.assertIn("| 0.40 | epsilon | zeta |", section)
            self.assertNotIn("gamma", section)
            self.assertNotIn("delta", section)

    def test_pair_just_below_the_threshold_is_left_out(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            work = Path(temporary)
            default = collision_section(self.audit(work))
            loose = collision_section(self.audit(work, "--threshold", "0.3"))

            self.assertNotIn("| eta |", default)
            self.assertIn("| 0.33 | eta | theta |", loose)

    def test_threshold_flag_replaces_the_default(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            strict = collision_section(
                self.audit(Path(temporary), "--threshold", "0.8")
            )

            self.assertNotIn("alpha", strict)
            self.assertIn("No pair at or above threshold 0.80", strict)

    def test_threshold_outside_zero_to_one_is_a_usage_error(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            for bad in ("nan", "-0.1", "1.5"):
                result = subprocess.run(
                    [
                        sys.executable,
                        str(SCRIPT),
                        "--root",
                        str(Path(temporary)),
                        "--threshold",
                        bad,
                    ],
                    capture_output=True,
                    text=True,
                    check=False,
                )

                self.assertEqual(result.returncode, 2, f"--threshold {bad}")
                self.assertIn("threshold", result.stderr)

    def test_description_case_does_not_change_the_score(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            section = collision_section(
                self.audit(
                    Path(temporary),
                    skills=(
                        ("loud", "REVIEWS Frontend ACCESSIBILITY focus states."),
                        ("quiet", "reviews frontend accessibility focus states."),
                    ),
                )
            )

            self.assertIn("| 1.00 | loud | quiet |", section)

    def test_two_runs_write_identical_bytes(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            work = Path(temporary)
            first = self.audit(work)
            second = self.audit(work)

            self.assertEqual(first, second)


class CheckModeTest(unittest.TestCase):
    def fixture_root(self, work: Path, skills=FIXTURES) -> Path:
        root = work / "root"
        root.mkdir(parents=True, exist_ok=True)
        for name, description in skills:
            write_skill(root, name, description)
        return root

    def test_clean_corpus_exits_zero_and_prints_nothing(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            work = Path(temporary)
            root = self.fixture_root(work, skills=APART)

            result = run_audit("--root", str(root), "--check")

            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(result.stdout, "")
            self.assertEqual(result.stderr, "")

    def test_collision_prints_one_classed_line_and_exits_one(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            work = Path(temporary)
            root = self.fixture_root(work, skills=COLLIDING)

            result = run_audit("--root", str(root), "--check")

            self.assertEqual(result.returncode, 1, result.stderr)
            self.assertEqual(result.stdout, "")
            self.assertEqual(
                result.stderr.splitlines(),
                ["collision: alpha / beta (0.75)"],
            )

    def test_shadowed_copy_prints_one_classed_line(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            work = Path(temporary)
            first = self.fixture_root(work / "first", skills=APART)
            second = work / "second"
            write_skill(second, "gamma", "Drafts release notes for maintainers.")

            result = run_audit("--root", str(first), "--root", str(second), "--check")

            self.assertEqual(result.returncode, 1, result.stderr)
            lines = result.stderr.splitlines()
            self.assertEqual(len(lines), 1, lines)
            self.assertEqual(
                lines[0],
                f"shadowed: gamma at {second / 'gamma' / 'SKILL.md'} "
                f"(winner {first / 'gamma' / 'SKILL.md'})",
            )

    def test_threshold_applies_to_check_mode(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = self.fixture_root(Path(temporary), skills=AT_THRESHOLD)

            loose = run_audit("--root", str(root), "--check", "--threshold", "0.41")
            tight = run_audit("--root", str(root), "--check", "--threshold", "0.40")

            self.assertEqual(loose.returncode, 0, loose.stderr)
            self.assertEqual(tight.returncode, 1, tight.stderr)
            self.assertEqual(tight.stderr, "collision: epsilon / zeta (0.40)\n")

    def test_check_leaves_the_report_byte_identical(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            work = Path(temporary)
            root = self.fixture_root(work)
            report = work / "report.md"
            report.write_text("sentinel\n", encoding="utf-8")

            result = run_audit("--root", str(root), "--out", str(report), "--check")

            self.assertEqual(result.returncode, 1, result.stderr)
            self.assertEqual(report.read_bytes(), b"sentinel\n")

    def test_check_creates_no_report_when_none_exists(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            work = Path(temporary)
            root = self.fixture_root(work)
            report = work / "report.md"

            run_audit("--root", str(root), "--out", str(report), "--check")

            self.assertFalse(report.exists())


class DeclaredAdvertisedTest(unittest.TestCase):
    DESCRIPTIONS = {
        "alpha": "Reviews frontend accessibility and focus states.",
        "beta": "Debugging database migrations and schema drift.",
    }

    def fixture_root(self, work: Path, extra_by_name: dict[str, str]) -> Path:
        root = work / "root"
        root.mkdir(parents=True, exist_ok=True)
        for name, extra in extra_by_name.items():
            write_skill(
                root,
                name,
                self.DESCRIPTIONS[name],
                extra_frontmatter=extra,
            )
        return root

    def test_hidden_declared_skill_prints_one_classed_line(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = self.fixture_root(
                Path(temporary), {"alpha": "disable-model-invocation: true"}
            )

            result = run_audit(
                "--root", str(root), "--check", "--require-advertised", "alpha"
            )

            self.assertEqual(result.returncode, 1, result.stderr)
            self.assertEqual(result.stdout, "")
            self.assertEqual(
                result.stderr.splitlines(),
                [f"hidden: alpha at {root / 'alpha' / 'SKILL.md'}"],
            )

    def test_opencode_autoinvoke_false_also_counts_as_hidden(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = self.fixture_root(
                Path(temporary), {"alpha": "opencode:\n  autoinvoke: false"}
            )

            result = run_audit(
                "--root", str(root), "--check", "--require-advertised", "alpha"
            )

            self.assertEqual(result.returncode, 1, result.stderr)
            self.assertEqual(
                result.stderr.splitlines(),
                [f"hidden: alpha at {root / 'alpha' / 'SKILL.md'}"],
            )

    def test_opencode_autoinvoke_true_stays_advertised(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = self.fixture_root(
                Path(temporary), {"alpha": "opencode:\n  autoinvoke: true"}
            )

            result = run_audit(
                "--root", str(root), "--check", "--require-advertised", "alpha"
            )

            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(result.stderr, "")

    def test_missing_declared_skill_fails_the_check(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = self.fixture_root(Path(temporary), {"alpha": ""})

            result = run_audit(
                "--root", str(root), "--check", "--require-advertised", "ghost"
            )

            self.assertEqual(result.returncode, 1, result.stderr)
            self.assertEqual(result.stdout, "")
            self.assertEqual(result.stderr.splitlines(), ["missing: ghost"])

    def test_present_unflagged_declared_skill_exits_zero(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = self.fixture_root(Path(temporary), {"alpha": ""})

            result = run_audit(
                "--root", str(root), "--check", "--require-advertised", "alpha"
            )

            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(result.stderr, "")

    def test_require_advertised_without_check_is_a_usage_error(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = self.fixture_root(Path(temporary), {"alpha": ""})

            result = run_audit("--root", str(root), "--require-advertised", "alpha")

            self.assertEqual(result.returncode, 2, result.stderr)
            self.assertIn("--require-advertised requires --check", result.stderr)

    def test_declared_option_is_repeatable(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = self.fixture_root(
                Path(temporary),
                {"alpha": "", "beta": "disable-model-invocation: true"},
            )

            result = run_audit(
                "--root",
                str(root),
                "--check",
                "--require-advertised",
                "alpha",
                "--require-advertised",
                "beta",
            )

            self.assertEqual(result.returncode, 1, result.stderr)
            self.assertEqual(
                result.stderr.splitlines(),
                [f"hidden: beta at {root / 'beta' / 'SKILL.md'}"],
            )


